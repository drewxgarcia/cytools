"""Reproduce the hole tables of arXiv:2603.11173 (Gendler, Sheridan, Stillman, Wu
-- "Holes in Calabi-Yau Effective Cones") with this fork.

A *non-trivial Hilbert basis element* is an element of the Hilbert basis of the
toric effective cone E_V (the cone generated by the classes of prime toric
divisors, in CYTools' deterministic default divisor basis) that is not itself
the class of a prime toric divisor.  The paper's claim is that all of these are
"holes": effective-cone lattice points with no global sections.

Reproduced here: the *enumeration* -- which geometries have them, and what the
classes are.  E_V depends only on the polytope (not the triangulation), so this
is one computation per birational class, as in the paper.
"""

import argparse
import os
import sys
import time

os.environ.setdefault("CYTOOLS_DB_DIR", os.path.expanduser("~/Downloads/polytopes-4d"))

# Paper tables, keyed by h11 -> {h21: sorted list of classes (as tuples)}
# h11=2: sec 4.2 text (a single geometry).  h11=3: Table 2 (complete).
# h11=4,5,6: Tables 3,4,5 -- *interior* (big) elements only.
PAPER_H11_2 = {106: [(1, -1)]}
PAPER_H11_3 = {
    43: [(1, -1, 1)],
    45: [(1, -1, 0), (1, 0, -1)],
    51: [(-1, 1, 1)],
    59: [(1, -1, 1)],
    63: [(1, -1, 1)],
    83: [(1, -1, 1)],
    89: [(-1, 2, 2)],
    93: [(1, -1, 1)],
    95: [(-1, 4, -1)],
    99: [(1, -1, 1)],
    105: [(1, -1, 0), (1, -2, -2)],
    165: [(3, -1, 1)],
}
PAPER_INTERIOR = {
    4: {
        94: [(1, 0, -2, -1)],
        112: [(-1, 1, 1, 0), (5, -1, -1, 2)],
    },  # 3 geometries at h21=112
    5: {
        57: [(-3, 2, -2, 1, -1)],
        77: [(1, -2, -2, 0, -1), (1, 0, -2, -1, -1)],
        95: [(1, -1, -2, -1, 1)],
    },
    6: {
        42: [(1, 1, -1, 1, 1, 1)],
        52: [(1, -2, -3, -2, -2, -1)],
        60: [(1, 0, -2, -1, -2, -1), (1, -2, -1, -1, 1, -2), (-1, 1, 1, 0, 1, 0)],
        64: [(1, 0, -2, -2, -1, -1)],
        66: [(-1, 0, 5, 2, 3, 2), (1, -2, -2, 0, -2, -1)],
        78: [(1, -1, -2, -1, 1)],
    },
}
# "For h11=4, we have a total of 88 Calabi-Yau threefolds with holes" (sec 4.4)
PAPER_TOTALS = {2: 1, 3: 13, 4: 88}


def scan_one(verts):
    """Return (h21, non-trivial HB elements, which are strictly interior)."""
    from cytools import Polytope

    p = Polytope(verts)
    if not p.is_favorable(lattice="N"):
        return None
    cy = p.triangulate().get_cy()
    Q = cy.glsm_charge_matrix(include_origin=False)
    ec = cy.toric_effective_cone()
    prime = {tuple(int(x) for x in c) for c in Q.T}
    nt, interior = [], []
    for h in ec.hilbert_basis():
        t = tuple(int(x) for x in h)
        if t in prime:
            continue
        nt.append(t)
        # strictly interior to E_V  <=>  big on V.  E_V = {x : A x >= 0} with
        # A the facet normals; strict interior means all inequalities strict.
        A = ec.hyperplanes()
        interior.append(bool((A @ h > 0).all()))
    if not nt:
        return None
    return (int(cy.h21()), nt, interior)


def _worker(v):
    try:
        return scan_one(v)
    except Exception as e:
        return ("ERR", repr(e))


def run(h11, workers):
    from cytools.dataset import load_polytopes

    t0 = time.time()
    recs = load_polytopes(h12=h11)
    verts = [r.polytope.vertices().tolist() for r in recs]
    t_load = time.time() - t0

    t0 = time.time()
    if workers == 1:
        out = [_worker(v) for v in verts]
    else:
        import multiprocessing as mp
        from concurrent.futures import ProcessPoolExecutor

        with ProcessPoolExecutor(
            max_workers=workers, mp_context=mp.get_context("spawn")
        ) as ex:
            out = list(ex.map(_worker, verts, chunksize=8))
    t_calc = time.time() - t0

    errs = [o for o in out if o and o[0] == "ERR"]
    hits = [o for o in out if o and o[0] != "ERR"]
    n_interior_geoms = sum(1 for _, _, ii in hits if any(ii))

    print(
        f"\n=== h11 = {h11} ===  ({len(verts)} polytopes, load {t_load:.1f}s, "
        f"compute {t_calc:.1f}s, workers={workers})"
    )
    if errs:
        print(f"  !! {len(errs)} errors, first: {errs[0][1]}")
    print(
        f"  favorable geometries with non-trivial Hilbert basis elements: "
        f"{len(hits)}"
        + (f"   (paper: {PAPER_TOTALS[h11]})" if h11 in PAPER_TOTALS else "")
    )
    print(f"  ...of which have a strictly-interior (big) one: {n_interior_geoms}")

    # compare against paper, grouped by h21
    from collections import defaultdict

    mine = defaultdict(list)
    mine_int = defaultdict(list)
    for h21, nt, ii in hits:
        mine[h21].extend(nt)
        mine_int[h21].extend(c for c, i in zip(nt, ii) if i)

    if h11 == 2:
        paper, ours, what = PAPER_H11_2, mine, "all non-trivial HB elements"
    elif h11 == 3:
        paper, ours, what = PAPER_H11_3, mine, "all non-trivial HB elements"
    elif h11 in PAPER_INTERIOR:
        paper, ours, what = PAPER_INTERIOR[h11], mine_int, "interior-only"
    else:
        paper = None

    if paper is not None:
        print(f"  comparison ({what}), keyed by h^2,1:")
        keys = sorted(set(paper) | set(ours))
        allok = True
        for k in keys:
            pv = sorted(paper.get(k, []))
            ov = sorted(ours.get(k, []))
            ok = pv == ov
            allok &= ok
            print(f"    h21={k:<4} fork={ov}")
            print(f"    {'':<9} paper={pv}   {'MATCH' if ok else 'DIFF'}")
        print(f"  --> h11={h11}: {'ALL MATCH' if allok else 'MISMATCH'}")
    sys.stdout.flush()
    return hits


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--h11", type=int, nargs="+", default=[2, 3])
    ap.add_argument("--workers", type=int, default=1)
    a = ap.parse_args()
    for k in a.h11:
        run(k, a.workers)
